//Operador Ternário
//Sintaxe: condição ? valor_se_verdadeiro : valor_se_falso
const nota = 7.5;
const status = nota >= 6 ? 'Aprovado' : 'Reprovado';
console.log(status);

//Exemplo com múltiplas condições aninhadas
const idade = 15;
const categoria = idade < 12 ? 'Criança' : idade < 18 ? 'Adolescente' : 'Adulto';
console.log(categoria); //"Adolescente"

